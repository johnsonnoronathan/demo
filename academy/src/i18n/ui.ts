const DICTS: Record<Locale, Dict> = { en, zh, ja, ko, es, fr, de };

export function t(locale: Locale, key: UIKey, vars: Record<string, string | number> = {}): string {
  const s = DICTS[locale][key] ?? en[key];
  return s.replace(/\{(\w+)\}/g, (_, k) => String(vars[k] ?? `{${k}}`));
}

/** Strings the browser needs (player, copy buttons, progress), for one locale. */
export function clientStrings(locale: Locale) {
  const keys = Object.keys(en).filter((k) => /^(video|agent|scene|quiz|learning|lesson\.(markComplete|completed)|course\.(continue|review|done)|plan\.(copied|copyBlocked|copy))\b/.test(k)) as UIKey[];
  return Object.fromEntries(keys.map((k) => [k, t(locale, k)]));
}

export function formatMinutes(locale: Locale, min: number) {
  const h = Math.floor(min / 60), m = min % 60;
  const units: Record<Locale, [string, string]> = {
    en: ["h", "min"], zh: ["小时", "分钟"], ja: ["時間", "分"], ko: ["시간", "분"], es: ["h", "min"], fr: ["h", "min"], de: ["Std.", "Min."],
  };
  const [H, M] = units[locale];
  const cjk = locale === "zh" || locale === "ja" || locale === "ko";
  const join = (n: number, u: string) => (cjk ? `${n} ${u}` : `${n} ${u}`);
  if (!h) return join(m, M);
  return m ? `${join(h, H)} ${join(m, M)}` : join(h, H);
}

export function formatClock(sec: number) {
  sec = Math.max(0, Math.round(sec));
  return `${Math.floor(sec / 60)}:${String(sec % 60).padStart(2, "0")}`;
}
